// Local-only browser verification using the already installed Chrome.
const { chromium } = require('playwright-core');
const fs = require('node:fs');
const path = require('node:path');
const assert = require('node:assert/strict');
(async () => {
  const out = path.resolve(__dirname, process.argv.includes('--wood') ? '../diagnostics/wood-preview' : '../diagnostics/web-preview');
  const browser = await chromium.launch({ executablePath: 'C:/Program Files/Google/Chrome/Application/chrome.exe', headless: true });
  try {
    const page = await browser.newPage({ viewport: { width: 1440, height: 1100 }, deviceScaleFactor: 1 });
    const errors = [];
    page.on('pageerror', e => errors.push(String(e)));
    page.on('console', m => { if(m.type()==='error') errors.push(m.text()); });
    page.on('response',r=>{if(r.status()>=400) console.log('HTTP failure',r.status(),r.url());});
    await page.goto('http://127.0.0.1:4173/');
    await page.waitForFunction(() => !!window.Sawara?.viewer, { timeout: 45000 });
    const state = await page.evaluate(() => {
      const v = window.Sawara.viewer;
      return { camera:v.camera.position.toArray(), aspect:v.camera.aspect, info:v.renderer.info.render, meshes:v.model.children.length, mode:v.getMode() };
    });
    assert(state.info.calls > 0, 'Model must actually draw');
    const checks=[];
    const cameraState=()=>page.evaluate(()=>({position:window.Sawara.viewer.camera.position.toArray(),distance:window.Sawara.viewer.camera.position.distanceTo({x:0,y:8,z:0})}));
    const start=await cameraState();
    await page.waitForTimeout(350);
    const rotated=await cameraState();
    assert(Math.hypot(...rotated.position.map((v,i)=>v-start.position[i]))>.1,'Auto rotation'); checks.push('Auto rotation');
    const canvas=page.locator('#stage canvas');
    const rect=await canvas.boundingBox();const x=rect.x+rect.width/2,y=rect.y+rect.height/2;
    await page.mouse.move(x,y);await page.mouse.wheel(0,-350);await page.waitForTimeout(350);
    const zoomed=await cameraState();assert(zoomed.distance<rotated.distance,'Wheel up zooms in');checks.push('Wheel zoom');
    await page.mouse.down({button:'right'});await page.waitForTimeout(200);
    const hold=await cameraState();await page.waitForTimeout(200);const held=await cameraState();
    assert(Math.hypot(...held.position.map((v,i)=>v-hold.position[i]))<.01,'Auto rotation pauses while dragging');
    await page.mouse.move(x+100,y+40,{steps:10});await page.mouse.up({button:'right'});
    const dragged=await cameraState();assert(Math.hypot(...dragged.position.map((v,i)=>v-held.position[i]))>1,'Right drag rotates');checks.push('Right drag and auto pause');
    // Restore the designed framing for the exterior screenshot.
    await page.reload();await page.waitForFunction(()=>!!window.Sawara?.viewer);await page.waitForTimeout(150);
    await page.screenshot({ path:path.join(out,'A-exterior-browser.png') });
    const box=await page.locator('#stage canvas').boundingBox();
    await page.mouse.click(box.x+box.width/2,box.y+box.height/2);
    await page.waitForTimeout(2000);
    await page.waitForFunction(()=>!window.Sawara.viewer.isTransitioning());
    assert.equal(await page.evaluate(()=>window.Sawara.viewer.getMode()),'guide');
    assert.equal(await page.locator('#guide-button').getAttribute('aria-pressed'),'true');checks.push('Canvas click enters guide');
    const fixed=await cameraState();await page.waitForTimeout(250);const still=await cameraState();
    assert(Math.hypot(...still.position.map((v,i)=>v-fixed.position[i]))<.001,'Guide camera fixed');checks.push('Guide camera fixed');
    await page.locator('[data-select-floor="3f"]').click();
    assert.equal(await page.locator('[data-select-floor="3f"]').getAttribute('aria-pressed'),'true');checks.push('Floor selection');
    await page.screenshot({path:path.join(out,'B-guide-browser.png')});
    await page.locator('#archives').scrollIntoViewIfNeeded();
    await page.screenshot({path:path.join(out,'C-archives-browser.png')});
    await page.locator('#archive-links a').first().click();await page.waitForURL('**/archives.html#b1f');
    assert(await page.locator('#b1f').isVisible());checks.push('B1F destination');
    const mobile=await browser.newContext({viewport:{width:390,height:844},isMobile:true,hasTouch:true,deviceScaleFactor:1});
    const mp=await mobile.newPage();await mp.goto('http://127.0.0.1:4173/');await mp.waitForFunction(()=>!!window.Sawara?.viewer);
    const ms=await mp.locator('#stage canvas').boundingBox();
    const cdp=await mobile.newCDPSession(mp);
    const touch=(type,points)=>cdp.send('Input.dispatchTouchEvent',{type,touchPoints:points});
    const sx=ms.x+ms.width/2,sy=ms.y+ms.height/2;
    await mp.locator('#rotate-button').click();
    const mbefore=await mp.evaluate(()=>window.Sawara.viewer.camera.position.toArray());
    await touch('touchStart',[{x:sx,y:sy,id:1}]);
    await touch('touchMove',[{x:sx+50,y:sy+20,id:1}]);await touch('touchEnd',[]);await mp.waitForTimeout(150);
    const mafter=await mp.evaluate(()=>window.Sawara.viewer.camera.position.toArray());
    assert(Math.hypot(...mafter.map((v,i)=>v-mbefore[i]))>.1,'Touch rotates');checks.push('Touch rotation');
    const beforePinch=await mp.evaluate(()=>window.Sawara.viewer.camera.position.distanceTo({x:0,y:8,z:0}));
    await touch('touchStart',[{x:sx-20,y:sy,id:1},{x:sx+20,y:sy,id:2}]);
    await touch('touchMove',[{x:sx-50,y:sy,id:1},{x:sx+50,y:sy,id:2}]);await touch('touchEnd',[]);await mp.waitForTimeout(150);
    const afterPinch=await mp.evaluate(()=>window.Sawara.viewer.camera.position.distanceTo({x:0,y:8,z:0}));
    assert(afterPinch<beforePinch,'Pinch zoom');checks.push('Pinch zoom');
    await mp.locator('#guide-button').click();await mp.waitForTimeout(1800);
    await mp.waitForFunction(()=>!window.Sawara.viewer.isTransitioning());
    assert.equal(await mp.evaluate(()=>window.Sawara.viewer.getMode()),'guide');
    assert(await mp.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),'No mobile overflow');
    await mp.screenshot({path:path.join(out,'mobile-guide-browser.png'),fullPage:true});checks.push('Mobile guide and layout');
    await mobile.close();
    const fallback=await browser.newContext({reducedMotion:'reduce'});
    const fp=await fallback.newPage();
    await fp.addInitScript(()=>{const original=HTMLCanvasElement.prototype.getContext;HTMLCanvasElement.prototype.getContext=function(type,...args){return type.startsWith('webgl')?null:original.call(this,type,...args);};});
    await fp.goto('http://127.0.0.1:4173/');
    await fp.waitForFunction(()=>document.getElementById('load-status').textContent.includes('この環境'));
    assert.equal(await fp.locator('#tenant-list a').count(),5);assert.equal(await fp.locator('#archive-links a').count(),3);checks.push('WebGL fallback navigation');
    await fallback.close();
    const reduced=await browser.newContext({reducedMotion:'reduce'});const rp=await reduced.newPage();
    await rp.goto('http://127.0.0.1:4173/');await rp.waitForFunction(()=>!!window.Sawara?.viewer);
    assert.equal(await rp.locator('#rotate-button').getAttribute('aria-pressed'),'false');checks.push('Reduced motion');await reduced.close();
    console.log('Browser console errors',errors);
    assert.equal(errors.length,0,'No page or console errors');
    fs.writeFileSync(path.join(out,'browser-check.json'),JSON.stringify({state,checks,errors},null,2));
    console.log(JSON.stringify({checks,errors}));
  } finally { await browser.close(); }
})().catch(error => { console.error(error); process.exitCode=1; });
